# ============================================================
# Canonical AI Request and Prediction Contracts
# ============================================================
# Permanent platform boundary for AI vulnerability inference.
# All providers must consume CanonicalAIRequest and return
# list[CanonicalAIPrediction].
# ============================================================

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any


class AIErrorCode(str, Enum):
    """Structured, safe failure codes for AI inference operations."""
    UNSUPPORTED_LANGUAGE = "UNSUPPORTED_LANGUAGE"
    INVALID_GRAPH = "INVALID_GRAPH"
    FEATURE_SCHEMA_MISMATCH = "FEATURE_SCHEMA_MISMATCH"
    MODEL_INPUT_INVALID = "MODEL_INPUT_INVALID"
    MODEL_NOT_READY = "MODEL_NOT_READY"
    INPUT_TOO_LARGE = "INPUT_TOO_LARGE"
    INFERENCE_TIMEOUT = "INFERENCE_TIMEOUT"
    PROVIDER_UNAVAILABLE = "PROVIDER_UNAVAILABLE"


class AIInferenceError(Exception):
    """Structured exception raised when AI provider encounters an error."""

    def __init__(self, code: AIErrorCode, message: str, details: dict[str, Any] | None = None):
        super().__init__(message)
        self.code = code
        self.message = message
        self.details = details or {}


@dataclass(frozen=True)
class SourceFileContext:
    """Metadata and content reference for a source file in the snapshot."""
    file_id: uuid.UUID
    relative_path: str
    language: str | None
    line_count: int
    content_hash: str
    original_artifact_uri: str


@dataclass(frozen=True)
class FunctionContext:
    """Metadata for an extracted function within a source file."""
    function_id: str
    name: str
    relative_path: str
    start_line: int
    end_line: int
    signature: str | None
    token_count: int


@dataclass(frozen=True)
class CanonicalAIRequest:
    """Stable, canonical AI inference request.
    
    Carries snapshot identity, source/function context, and references
    to Phase 4 canonical graph artifacts and taint evidence.
    """
    scan_id: uuid.UUID
    source_snapshot_id: uuid.UUID
    project_id: uuid.UUID
    language: str | None
    source_files: list[SourceFileContext] = field(default_factory=list)
    functions: list[FunctionContext] = field(default_factory=list)
    graph_artifact_refs: dict[str, str] = field(default_factory=dict)  # artifact_type -> storage_key / artifact_id
    cpg_ref: str | None = None
    taint_evidence_ref: str | None = None
    feature_schema_version: str = "v1.0.0"
    requested_task: str = "vulnerability_detection"
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class CanonicalAIPrediction:
    """Stable, canonical AI inference prediction.
    
    Represents an atomic vulnerability detection hypothesis generated by
    an AI model or provider.
    """
    file_path: str
    function_name: str | None
    line_number: int | None
    end_line: int | None
    prediction: str  # "VULNERABLE" or "BENIGN"
    confidence: float  # 0.0 to 1.0
    cwe_id: str | None  # e.g. "CWE-89"
    severity: str  # "critical", "high", "medium", "low"
    cvss_score: float | None  # 0.0 to 10.0
    evidence: dict[str, Any] = field(default_factory=dict)
    provider: str = "unknown"
    model_name: str = "unknown"
    model_version: str = "v1.0.0"
    input_schema_version: str = "v1.0.0"
    output_schema_version: str = "v1.0.0"
    generated_by_ai: bool = True
    inference_timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    provenance_metadata: dict[str, Any] = field(default_factory=dict)
